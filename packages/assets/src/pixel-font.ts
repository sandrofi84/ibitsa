/** How tall each glyph cell is, the distance between lines, and the gap after each glyph. */
export const FONT_CELL = 8;
export const FONT_LINE = 9;
const BASELINE = 6;
const GAP = 1;

/** The face name, which the game loads the font by. */
export const FONT_FACE = 'ibitsa-pixel';

function rows(char: string): string[] {
  const grid = (GLYPHS[char] as string).split('/');
  const width = grid[0]?.length ?? 0;
  if (grid.some((r) => r.length !== width) || grid.length < BASELINE || grid.length > FONT_CELL)
    throw new Error(`Glyph ${JSON.stringify(char)} isn't a ${width}-wide grid of 6 to 8 rows.`);
  return grid;
}

/** The font's image, every glyph side by side, and its BMFont description (XML), which Phaser reads. */
export function pixelFont(): PixelFont {
  const chars = Object.keys(GLYPHS);
  const grids = chars.map(rows);
  const width = grids.reduce((sum, g) => sum + (g[0]?.length ?? 0) + GAP, 0);
  const image = new Raster(width, FONT_CELL);
  const white = hex('#ffffff');
  const entries: string[] = [];
  let x = 0;
  chars.forEach((char, i) => {
    const grid = grids[i] as string[];
    const w = grid[0]?.length ?? 0;
    grid.forEach((row, y) => {
      for (let k = 0; k < w; k++) if (row[k] === '#') image.set({ x: x + k, y, color: white });
    });
    const id = char.codePointAt(0);
    entries.push(
      `    <char id="${id}" x="${x}" y="0" width="${w}" height="${FONT_CELL}" xoffset="0" yoffset="0" xadvance="${w + GAP}" page="0" chnl="15"/>`,
    );
    x += w + GAP;
  });
  const xml = [
    '<?xml version="1.0"?>',
    '<font>',
    `  <info face="${FONT_FACE}" size="${FONT_CELL}" bold="0" italic="0" smooth="0"/>`,
    `  <common lineHeight="${FONT_LINE}" base="${BASELINE}" scaleW="${width}" scaleH="${FONT_CELL}" pages="1"/>`,
    `  <pages><page id="0" file="${FONT_FACE}.png"/></pages>`,
    `  <chars count="${chars.length}">`,
    ...entries,
    '  </chars>',
    '</font>',
    '',
  ].join('\n');
  return { image, xml, chars };
}
